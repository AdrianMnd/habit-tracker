package com.adrian.habittracker.security;

import com.adrian.habittracker.entity.User;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;

import java.util.Collection;
import java.util.List;

/**
 * Spring Security trabaja con su propia interfaz UserDetails, no con
 * nuestra entidad User directamente. Este adaptador envuelve el User real
 * para que el resto de Spring Security (y nuestros controllers, via
 * @AuthenticationPrincipal) puedan usarlo sin acoplarse a esa interfaz.
 */
public class UserPrincipal implements UserDetails {

    private final User user;

    public UserPrincipal(User user) {
        this.user = user;
    }

    public Long getId() {
        return user.getId();
    }

    public String getEmail() {
        return user.getEmail();
    }

    @Override
    public Collection<? extends GrantedAuthority> getAuthorities() {
        // No tenemos roles/permisos distintos todavia - todo usuario
        // autenticado tiene el mismo nivel de acceso a sus propios datos.
        return List.of();
    }

    @Override
    public String getPassword() {
        return user.getPasswordHash();
    }

    @Override
    public String getUsername() {
        return user.getEmail();
    }

    @Override
    public boolean isAccountNonExpired() {
        return true;
    }

    @Override
    public boolean isAccountNonLocked() {
        return true;
    }

    @Override
    public boolean isCredentialsNonExpired() {
        return true;
    }

    @Override
    public boolean isEnabled() {
        return true;
    }
}
